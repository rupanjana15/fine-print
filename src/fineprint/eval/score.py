"""Score saved predictions and rebuild the results table.

Every system writes data/predictions/<system>/<set>.jsonl with one {"id", "output"} per line
(`output` = the raw text the system produced, in the model's JSON format). This module turns that
into results/eval/<system>__<set>.json and regenerates results/RESULTS.md.

Usage:
    uv run python -m fineprint.eval.score <system> <set>   # score one run, then rebuild the table
    uv run python -m fineprint.eval.score --table           # only rebuild the table
"""

import argparse
import json
from datetime import date

from fineprint.config import RESULTS, data_path, load_config
from fineprint.eval.metrics import score
from fineprint.eval.sets import SETS, load_eval_set, set_fingerprint

EVAL_DIR = RESULTS / "eval"


def predictions_path(system: str, eval_set: str):
    path = data_path("predictions") / system
    path.mkdir(parents=True, exist_ok=True)
    return path / f"{eval_set}.jsonl"


def write_predictions(system: str, eval_set: str, outputs: dict[str, str], extra: dict | None = None):
    """Save outputs (id -> raw text). `extra` (id -> dict) adds fields such as timings."""
    with open(predictions_path(system, eval_set), "w") as f:
        for i, out in outputs.items():
            f.write(json.dumps({"id": i, "output": out, **(extra or {}).get(i, {})},
                               ensure_ascii=False) + "\n")


def read_predictions(system: str, eval_set: str) -> dict[str, dict]:
    with open(predictions_path(system, eval_set)) as f:
        return {r["id"]: r for r in map(json.loads, f)}


def score_run(system: str, eval_set: str, notes: str = "") -> dict:
    examples = load_eval_set(eval_set)
    preds = read_predictions(system, eval_set)
    space = (set(load_config("taxonomy")["lexglue_labels"].values())
             if eval_set == "lexglue" else None)
    metrics = score(examples, {i: p["output"] for i, p in preds.items()}, space)
    secs = [p["seconds"] for p in preds.values() if "seconds" in p]
    result = {
        "system": system, "eval_set": eval_set, "date": date.today().isoformat(),
        "dataset_version": load_config("data")["version"],
        "set_fingerprint": set_fingerprint(examples),
        "seconds_per_example": round(sum(secs) / len(secs), 3) if secs else None,
        "notes": notes, **metrics,
    }
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    (EVAL_DIR / f"{system}__{eval_set}.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def build_table() -> str:
    """results/RESULTS.md: one row per (system, set), the headline metrics only."""
    rows = [json.loads(p.read_text()) for p in sorted(EVAL_DIR.glob("*.json"))]
    order = {s: i for i, s in enumerate(SETS)}
    rows.sort(key=lambda r: (order.get(r["eval_set"], 99), r["system"]))
    head = ("| Set | System | Detect P | Detect R | Detect F1 | Cat macro-F1 | Severity acc | "
            "JSON valid | Quote faithful | Flag rate: neg / hard neg | s/example |")
    intro = ("Generated by `python -m fineprint.eval.score --table`; metric definitions in "
             "`src/fineprint/eval/metrics.py`, systems in docs/ARCHITECTURE.md §5.")
    lines = ["# Results", "", intro, "", head, "|" + "---|" * 11]

    def fmt(x):
        return "—" if x is None else f"{x:.3f}" if isinstance(x, float) else str(x)

    def neg_rates(r):
        k = r["flag_rate_by_kind"]
        return " / ".join(fmt(k.get(x)) for x in ("negative", "hard_negative") if x in k)

    for r in rows:
        d = r["detection"]
        lines.append("| " + " | ".join(fmt(v) for v in (
            r["eval_set"], r["system"], d["precision"], d["recall"], d["f1"],
            r["category_macro_f1"], r["severity_accuracy"], r["json_valid"],
            r["quote_faithfulness"], neg_rates(r), r["seconds_per_example"])) + " |")
    text = "\n".join(lines) + "\n"
    (RESULTS / "RESULTS.md").write_text(text)
    return text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("system", nargs="?")
    ap.add_argument("eval_set", nargs="?", choices=SETS)
    ap.add_argument("--table", action="store_true")
    args = ap.parse_args()
    if args.system:
        r = score_run(args.system, args.eval_set)
        print(json.dumps({k: v for k, v in r.items() if k != "per_category"}, indent=2))
    print(build_table())


if __name__ == "__main__":
    main()
